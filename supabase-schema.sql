create or replace function public.tks_store_is_open()
returns boolean
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  schedule jsonb;
  status jsonb;
  today jsonb;
  previous jsonb;
  weekday integer := extract(dow from (now() at time zone 'America/Sao_Paulo'))::integer;
  current_time_value time := (now() at time zone 'America/Sao_Paulo')::time;
  opening time;
  closing time;
begin
  select value into schedule from public.tks_settings where key = 'store_schedule';
  select value into status from public.tks_settings where key = 'store_status';
  if coalesce((status->>'manualOverride')::boolean, (status->>'manual_override')::boolean, false) is true
    or lower(coalesce(status->>'mode', 'open')) in ('paused', 'closed') then
    return lower(coalesce(status->>'mode', 'open')) = 'open';
  end if;
  if coalesce((schedule->>'enabled')::boolean, false) is not true then
    return lower(coalesce(status->>'mode', 'open')) = 'open';
  end if;

  select value into today
  from jsonb_array_elements(coalesce(schedule->'weekly', '[]'::jsonb)) item(value)
  where (value->>'day')::integer = weekday
  limit 1;
  select value into previous
  from jsonb_array_elements(coalesce(schedule->'weekly', '[]'::jsonb)) item(value)
  where (value->>'day')::integer = ((weekday + 6) % 7)
  limit 1;

  if today is not null and coalesce((today->>'enabled')::boolean, false) is true then
    opening := nullif(today->>'open', '')::time;
    closing := nullif(today->>'close', '')::time;
    if opening is not null and closing is not null and opening <> closing then
      if opening < closing then
        return current_time_value >= opening and current_time_value < closing;
      end if;
      if current_time_value >= opening then
        return true;
      end if;
    end if;
  end if;

  if previous is not null and coalesce((previous->>'enabled')::boolean, false) is true then
    opening := nullif(previous->>'open', '')::time;
    closing := nullif(previous->>'close', '')::time;
    if opening is not null and closing is not null and opening > closing and current_time_value < closing then
      return true;
    end if;
  end if;
  return false;
exception when others then
  return false;
end;
$$;

revoke all on function public.tks_store_is_open() from public;
grant execute on function public.tks_store_is_open() to anon, authenticated;

create or replace function public.tks_create_order(p_order jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  is_admin boolean := false;
  customer_name_value text;
  customer_phone_value text;
  payment_value text;
  payment_status_value text := 'pending';
  notes_value text;
  client_request_value text;
  source_value text;
  pricing jsonb := '{}'::jsonb;
  discount_type_value text := 'none';
  surcharge_type_value text := 'none';
  discount_input numeric(10,2) := 0;
  surcharge_input numeric(10,2) := 0;
  manual_discount_amount numeric(10,2) := 0;
  coupon_discount_amount numeric(10,2) := 0;
  surcharge_amount_value numeric(10,2) := 0;
  subtotal_value numeric(10,2) := 0;
  amount_received_value numeric(10,2);
  change_amount_value numeric(10,2) := 0;
  coupon_code_value text;
  coupon_row public.tks_promos%rowtype;
  input_items jsonb;
  item_row record;
  option_row record;
  product_row public.tks_products%rowtype;
  complement_row public.tks_complements%rowtype;
  validation_group record;
  complement_item jsonb;
  item_options jsonb;
  sanitized_items jsonb := '[]'::jsonb;
  product_id bigint;
  group_id bigint;
  option_id bigint;
  item_quantity integer;
  option_quantity integer;
  group_quantity integer;
  base_price numeric(10,2);
  extras_total numeric(10,2);
  line_total numeric(10,2);
  total_value numeric(10,2) := 0;
  existing_order_id bigint;
  created_order_id bigint;
begin
  if p_order is null or jsonb_typeof(p_order) <> 'object' then
    raise exception using errcode = '22023', message = 'Pedido inválido.';
  end if;

  if auth.uid() is not null then
    is_admin := public.tks_is_admin();
  end if;

  if not is_admin and not public.tks_store_is_open() then
    raise exception using errcode = 'P0001', message = 'O cardápio está fechado para novos pedidos.';
  end if;

  customer_name_value := trim(coalesce(p_order->>'customer_name', ''));
  customer_phone_value := regexp_replace(coalesce(p_order->>'customer_phone', ''), '[^0-9]', '', 'g');
  payment_value := trim(coalesce(p_order->>'payment', ''));
  payment_status_value := case when is_admin and lower(coalesce(p_order->>'payment_status', 'pending')) = 'paid' then 'paid' else 'pending' end;
  notes_value := trim(coalesce(p_order->>'notes', ''));
  client_request_value := nullif(trim(coalesce(p_order->>'client_request_id', '')), '');
  source_value := case when is_admin then coalesce(nullif(trim(p_order->>'order_source'), ''), 'pdv') else 'public' end;
  -- O público pode informar apenas o dinheiro recebido. Descontos, acréscimos
  -- e cupons continuam exclusivos do PDV autenticado.
  pricing := case
    when is_admin then coalesce(p_order->'pricing', '{}'::jsonb)
    else jsonb_build_object('amount_received', coalesce(p_order->'pricing'->>'amount_received', ''))
  end;
  input_items := coalesce(p_order->'items', '[]'::jsonb);

  if char_length(customer_name_value) not between 2 and 120 then
    raise exception using errcode = '22023', message = 'Nome do cliente inválido.';
  end if;
  if char_length(customer_phone_value) not between 10 and 15 then
    raise exception using errcode = '22023', message = 'Celular do cliente inválido.';
  end if;
  if char_length(notes_value) > 1000 then
    raise exception using errcode = '22023', message = 'Observação muito longa.';
  end if;
  if jsonb_typeof(input_items) <> 'array' or jsonb_array_length(input_items) not between 1 and 50 then
    raise exception using errcode = '22023', message = 'O pedido precisa ter entre 1 e 50 itens.';
  end if;

  if client_request_value is not null then
    select id into existing_order_id
    from public.tks_orders
    where client_request_id = client_request_value
    limit 1;
    if existing_order_id is not null then
      return jsonb_build_object('id', existing_order_id, 'deduplicated', true);
    end if;
  end if;

  for item_row in select value from jsonb_array_elements(input_items) as item(value) loop
    begin
      product_id := (item_row.value->>'id')::bigint;
      item_quantity := (item_row.value->>'qty')::integer;
    exception when invalid_text_representation then
      raise exception using errcode = '22023', message = 'Produto ou quantidade inválida.';
    end;

    if item_quantity not between 1 and 50 then
      raise exception using errcode = '22023', message = 'Quantidade de produto inválida.';
    end if;

    select * into product_row
    from public.tks_products
    where id = product_id and active = true;
    if not found then
      raise exception using errcode = '22023', message = 'Produto indisponível.';
    end if;

    base_price := round(coalesce(product_row.price, 0), 2);
    extras_total := 0;
    item_options := '[]'::jsonb;

    for option_row in select value from jsonb_array_elements(coalesce(item_row.value->'options', '[]'::jsonb)) as option(value) loop
      begin
        group_id := (option_row.value->>'groupId')::bigint;
        option_id := (option_row.value->>'itemId')::bigint;
        option_quantity := (option_row.value->>'qty')::integer;
      exception when invalid_text_representation then
        raise exception using errcode = '22023', message = 'Adicional inválido.';
      end;

      if option_quantity not between 1 and 50 then
        raise exception using errcode = '22023', message = 'Quantidade de adicional inválida.';
      end if;

      select * into complement_row
      from public.tks_complements candidate_group
      where candidate_group.id = group_id
        and candidate_group.active = true
        and (
          exists (
            select 1 from jsonb_array_elements_text(coalesce(candidate_group.linked_product_ids, '[]'::jsonb)) linked(linked_product_id)
            where linked.linked_product_id = product_id::text
          )
          or (
            is_admin
            and lower(trim(coalesce(product_row.cat, ''))) not in ('bebidas', 'combos')
            and 'pdv-global' in (
              select jsonb_array_elements_text(coalesce(candidate_group.tags, '[]'::jsonb))
            )
          )
        );
      if not found then
        raise exception using errcode = '22023', message = 'Grupo de adicional inválido.';
      end if;

      select value into complement_item
      from jsonb_array_elements(coalesce(complement_row.items, '[]'::jsonb)) item(value)
      where (value->>'id')::bigint = option_id
        and coalesce((value->>'active')::boolean, true) = true
      limit 1;
      if complement_item is null then
        raise exception using errcode = '22023', message = 'Adicional indisponível.';
      end if;

      extras_total := extras_total + round(coalesce((complement_item->>'price')::numeric, 0), 2) * option_quantity;
      item_options := item_options || jsonb_build_array(jsonb_build_object(
        'groupId', group_id,
        'groupName', complement_row.name,
        'itemId', option_id,
        'name', complement_item->>'name',
        'price', round(coalesce((complement_item->>'price')::numeric, 0), 2),
        'qty', option_quantity
      ));
    end loop;

    for validation_group in
      select candidate_group.id, candidate_group.min_qty, candidate_group.max_qty
      from public.tks_complements candidate_group
      where candidate_group.active = true
        and (
          exists (
            select 1 from jsonb_array_elements_text(coalesce(candidate_group.linked_product_ids, '[]'::jsonb)) linked(linked_product_id)
            where linked.linked_product_id = product_id::text
          )
          or (
            is_admin
            and lower(trim(coalesce(product_row.cat, ''))) not in ('bebidas', 'combos')
            and 'pdv-global' in (
              select jsonb_array_elements_text(coalesce(candidate_group.tags, '[]'::jsonb))
            )
          )
        )
    loop
      select coalesce(sum((value->>'qty')::integer), 0) into group_quantity
      from jsonb_array_elements(item_options) selected(value)
      where (value->>'groupId')::bigint = validation_group.id;
      if group_quantity < coalesce(validation_group.min_qty, 0) or group_quantity > coalesce(validation_group.max_qty, 100) then
        raise exception using errcode = '22023', message = 'Quantidade de adicionais inválida.';
      end if;
    end loop;

    line_total := round((base_price + extras_total) * item_quantity, 2);
    total_value := total_value + line_total;
    sanitized_items := sanitized_items || jsonb_build_array(jsonb_build_object(
      'id', product_row.id,
      'name', product_row.name,
      'price', round(base_price + extras_total, 2),
      'basePrice', base_price,
      'qty', item_quantity,
      'options', item_options
    ));
  end loop;

  subtotal_value := round(total_value, 2);
  discount_type_value := lower(coalesce(nullif(trim(pricing->>'discount_type'), ''), 'none'));
  surcharge_type_value := lower(coalesce(nullif(trim(pricing->>'surcharge_type'), ''), 'none'));
  discount_input := coalesce(nullif(pricing->>'discount_value', ''), '0')::numeric;
  surcharge_input := coalesce(nullif(pricing->>'surcharge_value', ''), '0')::numeric;
  coupon_code_value := nullif(upper(trim(coalesce(pricing->>'coupon_code', ''))), '');
  amount_received_value := nullif(pricing->>'amount_received', '')::numeric;

  if discount_type_value not in ('none', 'fixed', 'percent') or surcharge_type_value not in ('none', 'fixed', 'percent') then
    raise exception using errcode = '22023', message = 'Tipo de ajuste inválido.';
  end if;
  if discount_input < 0 or surcharge_input < 0 then
    raise exception using errcode = '22023', message = 'Valor de ajuste inválido.';
  end if;
  if discount_type_value = 'percent' and discount_input > 100 then
    raise exception using errcode = '22023', message = 'Desconto percentual não pode passar de 100%.';
  end if;
  if surcharge_type_value = 'percent' and surcharge_input > 100 then
    raise exception using errcode = '22023', message = 'Acréscimo percentual não pode passar de 100%.';
  end if;

  manual_discount_amount := case
    when discount_type_value = 'percent' then round(subtotal_value * discount_input / 100, 2)
    when discount_type_value = 'fixed' then least(discount_input, subtotal_value)
    else 0
  end;

  if coupon_code_value is not null then
    select * into coupon_row
    from public.tks_promos
    where upper(code) = coupon_code_value
      and active = true
      and (starts_at is null or starts_at <= now())
      and (ends_at is null or ends_at >= now())
    limit 1;
    if not found or coupon_row.discount_type = 'none' or coupon_row.discount_value <= 0 then
      raise exception using errcode = '22023', message = 'Cupom inválido, inativo ou expirado.';
    end if;
    coupon_discount_amount := case
      when coupon_row.discount_type = 'percent' then round(greatest(subtotal_value - manual_discount_amount, 0) * least(coupon_row.discount_value, 100) / 100, 2)
      else least(coupon_row.discount_value, greatest(subtotal_value - manual_discount_amount, 0))
    end;
  end if;

  surcharge_amount_value := case
    when surcharge_type_value = 'percent' then round(greatest(subtotal_value - manual_discount_amount - coupon_discount_amount, 0) * surcharge_input / 100, 2)
    when surcharge_type_value = 'fixed' then surcharge_input
    else 0
  end;
  total_value := round(greatest(subtotal_value - manual_discount_amount - coupon_discount_amount, 0) + surcharge_amount_value, 2);
  if lower(payment_value) = 'dinheiro' then
    if amount_received_value is null or amount_received_value < total_value then
      raise exception using errcode = '22023', message = 'O valor recebido é menor que o total do pedido.';
    end if;
    change_amount_value := round(amount_received_value - total_value, 2);
  else
    amount_received_value := null;
    change_amount_value := 0;
  end if;

  insert into public.tks_orders (
    status, customer_name, customer_phone, payment, payment_status, notes, subtotal, discount_amount,
    coupon_code, coupon_discount_amount, surcharge_amount, amount_received, change_amount,
    total, items,
    order_source, client_request_id
  ) values (
    'Recebido', customer_name_value, customer_phone_value, payment_value, payment_status_value, notes_value,
    subtotal_value, manual_discount_amount, coupon_code_value, coupon_discount_amount,
    surcharge_amount_value, amount_received_value, change_amount_value,
    total_value, sanitized_items, source_value, client_request_value
  )
  on conflict (client_request_id) do nothing
  returning id into created_order_id;

  if created_order_id is null and client_request_value is not null then
    select id into created_order_id
    from public.tks_orders
    where client_request_id = client_request_value
    limit 1;
  end if;

  return jsonb_build_object(
    'id', created_order_id,
    'total', round(total_value, 2),
    'items', sanitized_items,
    'deduplicated', false
  );
end;
$$;

