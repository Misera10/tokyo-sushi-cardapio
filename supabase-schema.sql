create or replace function public.tks_close_cash_session(p_session_id bigint, p_counted_amount numeric)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  session_row public.tks_cash_sessions%rowtype;
  movements_in numeric(12,2);
  movements_out numeric(12,2);
  sales_total numeric(12,2);
  expected_total numeric(12,2);
begin
  if not public.tks_is_admin() then
    raise exception using errcode = '42501', message = 'Acesso negado.';
  end if;
  if p_counted_amount is null or p_counted_amount < 0 then
    raise exception using errcode = '22023', message = 'Valor contado inválido.';
  end if;

  select * into session_row
  from public.tks_cash_sessions
  where id = p_session_id and status = 'open'
  for update;
  if not found then
    raise exception using errcode = 'P0001', message = 'Caixa fechado ou inexistente.';
  end if;

  select coalesce(sum(amount) filter (where type = 'entrada'), 0),
         coalesce(sum(amount) filter (where type = 'saida'), 0)
  into movements_in, movements_out
  from public.tks_cash_movements
  where session_id = p_session_id;

  select coalesce(sum(total), 0) into sales_total
  from public.tks_orders
  where created_at >= session_row.opened_at
    and created_at <= now()
    and status <> 'Cancelado'
    and archived_at is null;

  expected_total := round(session_row.opening_amount + sales_total + movements_in - movements_out, 2);

  update public.tks_cash_sessions
  set status = 'closed',
      closed_at = now(),
      counted_amount = round(p_counted_amount, 2),
      expected_amount = expected_total,
      difference = round(p_counted_amount - expected_total, 2),
      closed_by = auth.uid()
  where id = p_session_id
  returning * into session_row;

  return jsonb_build_object(
    'id', session_row.id,
    'open', false,
    'opening', session_row.opening_amount,
    'openedAt', session_row.opened_at,
    'closedAt', session_row.closed_at,
    'countedAmount', session_row.counted_amount,
    'expectedAmount', session_row.expected_amount,
    'difference', session_row.difference,
    'transactions', '[]'::jsonb
  );
end;
$$;

